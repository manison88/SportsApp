#!/usr/bin/env python3
"""Builds the privacy policy and terms of use from legal/content.json and legal/config.json.
Writes: legal/privacy.html, legal/terms.html, analytics/legal.js (served by the analytics Worker at /privacy and /terms),
and Witness/Features/You/LegalContent.swift (the in-app copy). Edit the JSON files, then run: python3 Tools/legal/build.py
"""
import json, html, pathlib, re
root = pathlib.Path(__file__).resolve().parents[2]
cfg = json.load(open(root / "legal/config.json"))
content = json.load(open(root / "legal/content.json"))
values = {"app": cfg["app"], "company": cfg["company"], "email": cfg["email"], "jurisdiction": cfg["jurisdiction"],
          "retention": str(cfg["retention_months"])}
def fill(s): return re.sub(r"\{(\w+)\}", lambda m: values[m.group(1)], s)
unset = [k for k in ("company", "email", "jurisdiction") if cfg[k].startswith("[")]
if unset: print("WARNING: fill in legal/config.json:", ", ".join(unset))

CSS = """:root{color-scheme:light dark;--bg:#fff;--fg:#14130f;--mut:#6a665e;--acc:#b36b00}
@media(prefers-color-scheme:dark){:root{--bg:#050506;--fg:#f5f1ea;--mut:#9a958b;--acc:#ffb547}}
body{margin:0;background:var(--bg);color:var(--fg);font:17px/1.55 -apple-system,Inter,system-ui,sans-serif}
main{max-width:720px;margin:0 auto;padding:40px 22px 80px}h1{font:800 44px/1 'Barlow Condensed',Impact,sans-serif;text-transform:uppercase;margin:0 0 6px}
h2{font-size:20px;margin:34px 0 8px}p{margin:0 0 12px}.sum{font-size:19px}.date{color:var(--mut);margin:0 0 24px}
nav{margin-bottom:28px}nav a{color:var(--acc);margin-right:18px;text-decoration:none;font-weight:600}a{color:var(--acc)}"""

def page(key):
    d = content[key]
    body = "".join(f"<h2>{html.escape(fill(s['h']))}</h2>" + "".join(f"<p>{html.escape(fill(p))}</p>" for p in s["p"]) for s in d["sections"])
    return (f"<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\"><meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">"
            f"<title>{html.escape(cfg['app'])} {html.escape(d['title'])}</title><style>{CSS}</style></head><body><main>"
            f"<nav><a href=\"/privacy\">Privacy Policy</a><a href=\"/terms\">Terms of Use</a></nav>"
            f"<h1>{html.escape(d['title'])}</h1><p class=\"date\">{html.escape(cfg['app'])} · Effective {html.escape(cfg['effective'])}</p>"
            f"<p class=\"sum\">{html.escape(fill(d['summary']))}</p>{body}</main></body></html>")

privacy, terms = page("privacy"), page("terms")
(root / "legal/privacy.html").write_text(privacy)
(root / "legal/terms.html").write_text(terms)
(root / "analytics/legal.js").write_text("// Generated by Tools/legal/build.py. Do not edit.\nexport const PRIVACY_HTML = " + json.dumps(privacy) + ";\nexport const TERMS_HTML = " + json.dumps(terms) + ";\n")

def swift(s): return json.dumps(s, ensure_ascii=False)
def doc(key):
    d = content[key]
    secs = ",\n".join(f"            LegalDocument.Section(heading: {swift(fill(s['h']))}, paragraphs: [" + ", ".join(swift(fill(p)) for p in s["p"]) + "])" for s in d["sections"])
    return f"    static let {key} = LegalDocument(title: {swift(d['title'])}, effective: {swift(cfg['effective'])}, summary: {swift(fill(d['summary']))}, sections: [\n{secs},\n    ])"
(root / "Witness/Features/You/LegalContent.swift").write_text(
"""// Generated by Tools/legal/build.py from legal/content.json. Do not edit by hand.
import Foundation

struct LegalDocument: Identifiable {
    var id: String { title }
    struct Section { let heading: String; let paragraphs: [String] }
    let title: String
    let effective: String
    let summary: String
    let sections: [Section]
}

enum LegalContent {
""" + doc("privacy") + "\n\n" + doc("terms") + "\n}\n")
print("built")
